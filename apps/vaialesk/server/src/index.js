import "dotenv/config";
import { createClient } from "@supabase/supabase-js";
import { createRemoteJWKSet, jwtVerify } from "jose";
import { createApp } from "./app.js";
import { createRepository } from "./repository.js";
import { createLocalStore } from "./local-store.js";
for (const key of ["SUPABASE_URL", "SUPABASE_SERVICE_ROLE_KEY", "AUTH0_DOMAIN", "AUTH0_AUDIENCE"]) if (!process.env[key]) throw new Error(`Missing required environment variable: ${key}`);
const domain = process.env.AUTH0_DOMAIN.replace(/^https?:\/\//, "").replace(/\/$/, ""), issuer = `https://${domain}/`;
const jwks = createRemoteJWKSet(new URL(`${issuer}.well-known/jwks.json`));
const db = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false, autoRefreshToken: false } });
const store = await createLocalStore(process.env.OPERATIONS_FILE || new URL("../.data/operations.json", import.meta.url));
const app = createApp({ repository: createRepository(db), store, adminSubjects: (process.env.ADMIN_AUTH0_SUBS || "").split(",").map(s => s.trim()).filter(Boolean), verifyToken: async token => (await jwtVerify(token, jwks, { issuer, audience: process.env.AUTH0_AUDIENCE, algorithms: ["RS256"] })).payload });
app.listen(Number(process.env.PORT || 3000), "0.0.0.0", () => console.log(`Vaialesk API listening on port ${process.env.PORT || 3000}`));
